export function WhatsAppButton({ phone, message }: { phone: string | null; message?: string }) {
  if (!phone) return null;

  const digits = phone.replace(/\D/g, "");
  if (!digits) return null;

  const href = `https://wa.me/${digits}${message ? `?text=${encodeURIComponent(message)}` : ""}`;

  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      title="Conversar no WhatsApp"
      className="inline-flex items-center justify-center w-6 h-6 rounded-full hover:bg-green-50 transition-colors"
    >
      <svg viewBox="0 0 32 32" width="16" height="16" fill="#25D366">
        <path d="M16.001 3C9.373 3 4 8.373 4 15c0 2.386.7 4.61 1.902 6.478L4 29l7.72-1.867A11.94 11.94 0 0 0 16 27c6.627 0 12-5.373 12-12S22.628 3 16.001 3zm0 21.6c-1.98 0-3.83-.55-5.41-1.5l-.388-.23-4.58 1.107 1.128-4.463-.253-.4A9.55 9.55 0 0 1 5.4 15c0-5.85 4.76-10.6 10.601-10.6 5.84 0 10.6 4.75 10.6 10.6 0 5.85-4.76 10.6-10.6 10.6zm5.81-7.94c-.318-.16-1.884-.93-2.176-1.037-.291-.106-.504-.16-.716.16-.212.319-.822 1.037-1.008 1.25-.186.213-.371.24-.689.08-.318-.16-1.343-.495-2.559-1.578-.946-.844-1.585-1.885-1.77-2.204-.186-.319-.02-.492.14-.65.144-.144.318-.373.477-.56.16-.186.212-.319.318-.531.106-.213.053-.4-.027-.56-.08-.16-.716-1.726-.982-2.364-.259-.622-.522-.538-.716-.548-.186-.01-.398-.012-.61-.012-.213 0-.56.08-.85.4-.292.319-1.114 1.09-1.114 2.657 0 1.567 1.14 3.08 1.3 3.293.159.213 2.245 3.428 5.44 4.808.76.328 1.354.524 1.816.671.763.243 1.457.209 2.006.127.612-.091 1.884-.77 2.15-1.514.265-.744.265-1.38.186-1.514-.08-.133-.291-.213-.61-.373z" />
      </svg>
    </a>
  );
}
